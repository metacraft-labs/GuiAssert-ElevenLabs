type
  RecordedRequest = object
    httpMethod: string
    path: string
    query: string
    apiKeyHeader: string
    contentType: string
    accept: string
    body: string

# Shared global state for the mock server.  asynchttpserver's request
# handler is a `proc(req): Future[void]`, which can't easily close
# over per-test locals; globals are the path of least resistance.
var mockRequests: seq[RecordedRequest]
var mockResultMp3Path: string
var mockServerPort: int

proc firstHeader(h: HttpHeaders, name: string): string =
  if h.hasKey(name):
    let vals = h.table[name.toLowerAscii]
    if vals.len > 0: return vals[0]
  return ""

proc mockHandler(req: Request): Future[void] {.async, gcsafe.} =
  {.cast(gcsafe).}:
    var rec = RecordedRequest(
      httpMethod: $req.reqMethod,
      path: req.url.path,
      query: req.url.query,
      apiKeyHeader: firstHeader(req.headers, "xi-api-key"),
      contentType: firstHeader(req.headers, "content-type"),
      accept: firstHeader(req.headers, "accept"),
      body: req.body,
    )
    mockRequests.add rec

    let m = req.reqMethod
    let p = req.url.path

    if m == HttpPost and p.startsWith("/v1/text-to-speech/"):
      let bytes = readFile(mockResultMp3Path)
      await req.respond(Http200, bytes,
                        newHttpHeaders({"Content-Type": "audio/mpeg"}))
      return

    await req.respond(Http404, "mock: no route for " & $m & " " & p,
                      newHttpHeaders({"Content-Type": "text/plain"}))

proc pickFreePort(): int =
  let s = newSocket()
  s.bindAddr(Port(0))
  let (_, port) = s.getLocalAddr
  s.close()
  result = int(port)

var mockServerThread: Thread[int]
var mockServerStopFlag: bool

proc mockServerThreadProc(port: int) {.thread.} =
  {.cast(gcsafe).}:
    let server = newAsyncHttpServer()
    asyncCheck server.serve(Port(port), mockHandler, address = "127.0.0.1")
    while not mockServerStopFlag:
      poll(50)
    server.close()

proc startMockServer(): tuple[port: int, stop: proc() {.gcsafe.}] =
  let port = pickFreePort()
  mockServerPort = port
  mockRequests = @[]
  mockServerStopFlag = false
  createThread(mockServerThread, mockServerThreadProc, port)
  sleep(150)
  let stop = proc() {.gcsafe.} =
    mockServerStopFlag = true
    joinThread(mockServerThread)
  result = (port: port, stop: stop)

proc ffprobeJson(path: string): JsonNode =
  let ffprobe =
    block:
      let env = getEnv("FFPROBE_BIN")
      if env.len > 0 and fileExists(env): env
      else: findExe("ffprobe")
  doAssert ffprobe.len > 0 and fileExists(ffprobe),
    "ffprobe not on PATH; needed by the mock-server + live tests."
  let p = startProcess(
    command = ffprobe,
    args = @["-hide_banner", "-v", "error", "-print_format", "json",
             "-show_streams", "-show_format", path],
    options = {poStdErrToStdOut}
  )
  let raw = p.outputStream.readAll()
  let code = p.waitForExit()
  p.close()
  doAssert code == 0, "ffprobe failed (" & $code & "): " & raw
  parseJson(raw)

suite "elevenlabs mock-server integration":

  test "POST /v1/text-to-speech/{voice} downloads + converts to WAV + caches":
    let mp3 = ensureMockMp3()
    mockResultMp3Path = mp3

    let (port, stop) = startMockServer()
    defer: stop()

    let portStr = $port
    echo &"  mock server listening on http://localhost:{portStr}"

    let provider = elevenlabsProvider()

    let tmp = getTempDir() / "televenlabs_mock"
    if dirExists(tmp): removeDir(tmp)
    createDir(tmp)
    let outWav = tmp / "elevenlabs-mock.wav"
    let opts = SpeechSynthesisOpts(
      voiceId: none(string),
      rate: none(int),
      sampleRateHz: some(22050),
      cacheDir: some(tmp / "cache"),
      providerSettings: %*{
        "api_base": "http://localhost:" & portStr,
        "api_key": "DUMMY_KEY",
      },
      extraArgs: @[],
    )

    let started = epochTime()
    provider.synthesize("Hello from the ElevenLabs mock test.",
                       outWav, opts)
    let dt = epochTime() - started
    echo &"  mock round-trip took {dt*1000:.1f} ms"

    # ----- Recorded-request trace -----
    echo "  recorded requests (", $mockRequests.len, "):"
    for i, r in mockRequests:
      let bodyPreview =
        if r.body.len <= 240: r.body
        else: r.body[0 ..< 240] & " ...(+" & $(r.body.len - 240) &
          " bytes)"
      echo &"    [{i}] {r.httpMethod} {r.path} ?{r.query}"
      echo &"        xi-api-key: {r.apiKeyHeader}"
      echo &"        Content-Type: {r.contentType}"
      echo &"        Accept: {r.accept}"
      echo &"        body[{r.body.len}]: {bodyPreview}"

    # ----- Exactly one HTTP request: ElevenLabs has no polling step -----
    check mockRequests.len == 1

    # ----- Method + path -----
    check mockRequests[0].httpMethod == "POST"
    check mockRequests[0].path ==
      "/v1/text-to-speech/" & DefaultElevenLabsVoiceId

    # ----- xi-api-key header exact-string check -----
    check mockRequests[0].apiKeyHeader == "DUMMY_KEY"
    check mockRequests[0].contentType == "application/json"
    check mockRequests[0].accept == "audio/mpeg"

    # ----- POST body shape -----
    let body = parseJson(mockRequests[0].body)
    check body.kind == JObject
    check body["text"].getStr == "Hello from the ElevenLabs mock test."
    check body["model_id"].getStr == DefaultElevenLabsModelId
    check body["voice_settings"]["stability"].getFloat == 0.5
    check body["voice_settings"]["similarity_boost"].getFloat == 0.5

    # ----- The converted WAV exists, is non-empty, and is a valid
    #       PCM mono RIFF WAV at the requested sample rate -----
    check fileExists(outWav)
    let probe = ffprobeJson(outWav)
    let formatName = probe{"format", "format_name"}.getStr()
    echo &"  WAV format_name: {formatName}"
    check "wav" in formatName.toLowerAscii()
    var hasAudio = false
    var sampleRate = 0
    var channels = 0
    for s in probe{"streams"}.items:
      if s{"codec_type"}.getStr() == "audio":
        hasAudio = true
        let rNode = s{"sample_rate"}
        if not rNode.isNil and rNode.kind == JString:
          sampleRate = parseInt(rNode.getStr())
        channels = s{"channels"}.getInt()
    check hasAudio
    check sampleRate == 22050
    check channels == 1
    let dur = parseFloat(probe{"format", "duration"}.getStr())
    echo &"  WAV duration: {dur:.3f}s, sample_rate: {sampleRate}, " &
         &"channels: {channels}"
    # The mock served a 1-second silent MP3; the converted WAV should
    # be ~1 s ± codec slack.
    check dur >= 0.9
    check dur <= 1.5

    # ----- Cache hit on the second invocation skips HTTP entirely -----
    let beforeCount = mockRequests.len
    let outWav2 = tmp / "elevenlabs-mock-2.wav"
    let secondStart = epochTime()
    provider.synthesize("Hello from the ElevenLabs mock test.",
                       outWav2, opts)
    let secondDt = epochTime() - secondStart
    echo &"  cache-hit second call took {secondDt*1000:.1f} ms"
    check mockRequests.len == beforeCount  # no new HTTP traffic
    check fileExists(outWav2)
    check getFileSize(outWav2) == getFileSize(outWav)

    # ----- Cache miss when the narration text changes -----
    let outWav3 = tmp / "elevenlabs-mock-3.wav"
    provider.synthesize("A completely different narration.",
                       outWav3, opts)
    check mockRequests.len == beforeCount + 1
    check fileExists(outWav3)
    let createBody2 = parseJson(mockRequests[beforeCount].body)
    check createBody2["text"].getStr ==
      "A completely different narration."

