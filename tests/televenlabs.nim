## Unit + integration tests for the ElevenLabs GuiAssert plugin.
##
## ## Pure tests (always run)
##
##   * `elevenlabsAuthHeader` produces an `HttpHeaders` carrying the
##     documented lowercase `xi-api-key` value (no `Authorization`
##     header, no `Bearer ` prefix),
##   * `buildTtsBody` emits the expected JSON shape (`text`,
##     `model_id`, `voice_settings.stability`,
##     `voice_settings.similarity_boost`),
##   * `resolveApiKey` / `resolveApiBase` / `resolveModelId` /
##     `resolveVoiceId` / `resolveStability` / `resolveSimilarityBoost`
##     honour providerSettings -> env-var / default precedence,
##   * `elevenlabsProvider()` is wired up with the canonical name +
##     non-nil callbacks,
##   * `registerElevenLabs` integrates with the registry,
##   * `isAvailable()` reflects the presence of `ELEVENLABS_API_KEY`,
##   * cache-key determinism + per-input sensitivity (different
##     `voice_id` / `model_id` / sample rate / stability -> different
##     key).
##
## ## Mock-server integration test (always run, no network)
##
## A `std/asynchttpserver` mock spun up on a random free localhost
## port mirrors ElevenLabs's `POST /v1/text-to-speech/{voice_id}`
## endpoint.  The mock records every request (method, path, headers,
## body) so the test can then assert — by exact value — that the
## provider sent the `xi-api-key` header and the JSON body shape
## ElevenLabs expects.  The mock returns a 1-second silent MP3
## generated by ffmpeg as the "TTS result"; the test then verifies
## the provider's downloaded WAV is a valid 16-bit PCM mono RIFF WAV
## via ffprobe, and that a second invocation hits the on-disk cache
## and skips all HTTP.
##
## ## Live test (compile-time-gated via `-d:elevenlabsLive`)
##
##   nim c -d:elevenlabsLive -r --threads:on --hints:off \
##       --path:src --path:../GuiAssert/src tests/televenlabs.nim
##
## Requires `ELEVENLABS_API_KEY` to be set.  Per project policy, the
## live suite never silently skips: a missing key is a test failure.

